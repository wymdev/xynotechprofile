// Runs after `next build` (see package.json "build").
//
// 1. Hashes every inline <script> in the static export and builds a strict
//    Content-Security-Policy that allows only those exact scripts (no 'unsafe-inline').
// 2. Writes the policy for nginx (Docker/Coolify) -> build-security/csp.conf
// 3. Writes out/.htaccess for Apache (cPanel) with the same hardening.
// 4. Removes junk files (.DS_Store) from the export.

import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = "out";
const SEC = "build-security";

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const files = walk(OUT);

// ---- 4. junk files ----
for (const f of files) if (f.endsWith(".DS_Store")) rmSync(f);

// ---- 1. inline script hashes ----
const hashes = new Set();
const SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
for (const f of files.filter((f) => f.endsWith(".html"))) {
  const html = readFileSync(f, "utf8");
  for (const [, attrs, body] of html.matchAll(SCRIPT)) {
    if (/\bsrc\s*=/.test(attrs) || !body) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && !["text/javascript", "module", "application/javascript"].includes(type)) continue; // e.g. ld+json is not executed
    hashes.add(`'sha256-${createHash("sha256").update(body, "utf8").digest("base64")}'`);
  }
}

const CDN = "https://cdnjs.cloudflare.com";
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(" ")}`,
  `style-src 'self' 'unsafe-inline' ${CDN}`, // inline style attributes (React) + Font Awesome
  `font-src 'self' data: ${CDN}`,
  "img-src 'self' data: blob:",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "manifest-src 'self'",
  "media-src 'none'",
  "object-src 'none'",
  "frame-src 'none'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

// ---- 2. nginx ----
mkdirSync(SEC, { recursive: true });
writeFileSync(join(SEC, "csp.txt"), csp + "\n");
writeFileSync(join(SEC, "csp.conf"), `add_header Content-Security-Policy "${csp}" always;\n`);

// ---- 3. Apache / cPanel ----
const BOTS =
  "GPTBot|ChatGPT-User|OAI-SearchBot|CCBot|ClaudeBot|Claude-Web|anthropic-ai|Bytespider|Amazonbot|PerplexityBot|Google-Extended|Applebot-Extended|meta-externalagent|FacebookBot|Diffbot|ImagesiftBot|Omgilibot|cohere-ai|PetalBot|DataForSeoBot|AhrefsBot|SemrushBot|MJ12bot|DotBot|BLEXBot|MegaIndex|Scrapy|python-requests|python-urllib|aiohttp|httpx|Go-http-client|node-fetch|axios|libwww-perl|HTTrack|curl|Wget|zgrab|masscan|nikto|sqlmap|nmap";

const htaccess = `# Generated by scripts/postbuild-security.mjs — do not edit by hand.

# No directory listings, no content negotiation, no server signature
Options -Indexes -MultiViews
ServerSignature Off
DirectoryIndex index.html
ErrorDocument 404 /404.html
ErrorDocument 403 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Force HTTPS
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

  # Never serve hidden files (.git, .env, .htaccess …) except /.well-known
  RewriteRule (^|/)\\.(?!well-known/) - [F,L]

  # Static site: only GET and HEAD
  RewriteCond %{REQUEST_METHOD} !^(GET|HEAD)$
  RewriteRule ^ - [R=405,L]

  # Block scrapers, AI crawlers, attack tools and empty user agents
  RewriteCond %{HTTP_USER_AGENT} ^$ [OR]
  RewriteCond %{HTTP_USER_AGENT} (${BOTS}) [NC]
  RewriteRule ^ - [F,L]
</IfModule>

<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${csp}"
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
  Header always set Cross-Origin-Opener-Policy "same-origin"
  Header always set Cross-Origin-Resource-Policy "same-origin"
  # Share image and icon may be embedded by other sites (link previews)
  <FilesMatch "^(og\\.jpg|icon\\.svg)$">
    Header always set Cross-Origin-Resource-Policy "cross-origin"
  </FilesMatch>
  Header always set Strict-Transport-Security "max-age=31536000"
  Header always set X-Robots-Tag "noai, noimageai"
  Header always unset X-Powered-By
  Header unset X-Powered-By

  # Hashed build assets are immutable; pages always revalidate
  <If "%{REQUEST_URI} =~ m#^/_next/static/#">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </If>
  <Else>
    Header set Cache-Control "no-cache"
  </Else>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/plain text/css application/javascript application/json image/svg+xml application/xml
</IfModule>
`;
writeFileSync(join(OUT, ".htaccess"), htaccess);

console.log(`postbuild-security: ${hashes.size} inline script hashes, CSP + .htaccess written`);
